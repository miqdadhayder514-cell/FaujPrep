## The feature scan
When a figure changes from one box to the next, compare these features separately:
- **Count:** number of shapes, lines, dots, or shaded regions.
- **Position:** movement around corners, cells, or a centre point.
- **Direction:** rotation, reflection, or alternating orientation.
- **Shape and size:** one shape becoming another, or a size changing in steps.
- **Fill and line:** shaded versus empty, line thickness, or appearance of an added mark.

METHOD: Describe the rule in one sentence before looking at the answer choices. If your explanation needs several unrelated exceptions, it is probably not the intended simple pattern.

## Common practice formats
### Figure series
Compare each adjacent pair. Check a rotation or movement first, then count, fill, size, and alternation. For a repeating cycle, write the cycle length above the sequence. Verify your rule against every shown figure, not only the last two.

### Matrix questions
Check each row for a transformation, then check each column independently. Look for addition or removal of features, overlap, alternation, or a consistent movement. Do not assume that a row rule is enough if the columns show a second constraint.

### Analogy and transformation
State what happened to the first figure, such as “rotated one quarter-turn and gained one dot.” Apply the same transformation to the new figure. Keep the order of operations consistent.

### Odd-one-out and completion
Find a property shared by most options: number of sides, symmetry, direction, count, or fill. Test the candidate answer against the same property. In completion questions, solve the missing part from the surrounding pattern before comparing options.

