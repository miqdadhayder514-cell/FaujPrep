## Question-solving methods
### Analogies
Put the relationship into words: “a key opens a lock” or “a thermometer measures temperature.” Check the direction of the relationship and the part of speech. Then test the same relationship in the second pair. Reject an answer that is associated with the first word but does not have the same relationship.

### Letter and number series
Write the differences between adjacent terms. If differences are not constant, check whether they change regularly, alternate, or follow a multiplication/addition pattern. For letters, convert positions to numbers only when helpful and account for whether the sequence wraps after Z. Verify the proposed rule across the entire series.

### Classification and odd-one-out
Name the shared category or property for most choices. Check meanings, spelling patterns, use, and category membership; do not choose based only on how a word looks unless the task is about letters.

### Coding and decoding
Compare each original symbol or letter with its coded version. Test shifts, reversal, alternating rules, or substitutions using more than one example. A guessed rule that explains only one letter is not enough.

### Directions and relationships
Draw a small compass or family tree. Mark each move or relationship as it is stated, and do not rotate your point of view halfway through. For “facing” questions, distinguish a person's left/right from the page's left/right.

### Statements and conclusions
Treat each statement as a premise, even if it differs from what you know in real life. Accept a conclusion only when it must follow. “Some” does not mean “all”; a possibility is not certainty.

