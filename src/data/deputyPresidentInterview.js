function getDifficulty(categoryId, question) {
  if (categoryId === 'challenging-followups' || /what would you do|why should we select|conflicted|evidence supports|not recommended/i.test(question)) return 'challenging';
  if (/^(what is|who is|when did|name the|what are the three|what is the chemical)/i.test(question) || categoryId === 'general-knowledge-science') return 'easy';
  return 'moderate';
}

function slugify(value) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 72);
}

